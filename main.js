function dayHexagram(d, method = "plum-blossom") {
  const y = d.getFullYear();
  const m = d.getMonth() + 1;
  const day = d.getDate();
  const hour = d.getHours();
  if (method === "ymd-hash") {
    const seed = y * 372 + m * 31 + day;
    const upperNum2 = seed % 8 + 1;
    const lowerNum2 = (seed * 7 + 3) % 8 + 1;
    return castFromTrigrams(trigramByBagua(upperNum2), trigramByBagua(lowerNum2), []);
  }
  const upperNum = (y + m + day) % 8 + 1;
  const lowerNum = (y + m + day + hour) % 8 + 1;
  const changingLine = (y + m + day + hour) % 6 + 1;
  return castFromTrigrams(trigramByBagua(upperNum), trigramByBagua(lowerNum), [changingLine]);
}
